import { windowsAppEnvRestore, posixAppEnvRestore } from '../../shared/app-env-script'
import { posixCurlCommand } from '../agent-hooks/hook-post-command'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      ...windowsAppEnvRestore([
        'AGENT_HOOK_PORT',
        'AGENT_HOOK_ENDPOINT',
        'AGENT_HOOK_TOKEN',
        'AGENT_HOOK_ENV',
        'AGENT_HOOK_VERSION',
        'PANE_KEY',
        'TAB_ID',
        'WORKTREE_ID',
        'AGENT_LAUNCH_TOKEN'
      ]),
      'if "%ORCA_AGENT_HOOK_PORT%"=="" if defined ORCA_AGENT_HOOK_ENDPOINT if exist "%ORCA_AGENT_HOOK_ENDPOINT%" call "%ORCA_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%ORCA_AGENT_HOOK_TOKEN%"=="" if not "%ORCA_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\orca-dev\\agent-hooks" for /r "%APPDATA%\\orca-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      // Per-worktree `pnpm dev` profiles live one level down; FOR /R cannot take a FOR variable as its root.
      'if "%ORCA_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\orca-dev-wt" for /d %%P in ("%APPDATA%\\orca-dev-wt\\*") do call :scanEndpointDir "%%~fP\\agent-hooks"',
      'if "%ORCA_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\orca\\agent-hooks" for /r "%APPDATA%\\orca\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':scanEndpointDir',
      'if not "%ORCA_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'if exist "%~1" for /r "%~1" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%ORCA_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'set "orca_endpoint_port="',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set CODING_AGENT_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do set "orca_endpoint_port=%%P"',
      'if not defined orca_endpoint_port for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set ORCA_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do set "orca_endpoint_port=%%P"',
      'if "%orca_endpoint_port%"=="%ORCA_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      ...windowsAppEnvRestore([
        'AGENT_HOOK_PORT',
        'AGENT_HOOK_TOKEN',
        'AGENT_HOOK_ENV',
        'AGENT_HOOK_VERSION'
      ]),
      'exit /b 0',
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    posixAppEnvRestore([
      'AGENT_HOOK_PORT',
      'AGENT_HOOK_TOKEN',
      'AGENT_HOOK_ENV',
      'AGENT_HOOK_VERSION',
      'PANE_KEY',
      'TAB_ID',
      'WORKTREE_ID',
      'AGENT_LAUNCH_TOKEN',
      'AGENT_HOOK_ENDPOINT'
    ]),
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__orca_lookup_env() {',
    `awk -v modern="CODING_AGENT_\${1#ORCA_}" -v legacy="$1" 'index($0, modern "=") == 1 { current=substr($0, length(modern)+2); found=1 } index($0, legacy "=") == 1 { previous=substr($0, length(legacy)+2) } END { print found ? current : previous }'`,
    '}',
    '__orca_read_ancestor_var() {',
    '  __orca_name="$1"',
    '  __orca_pid="${PPID:-}"',
    '  while [ -n "$__orca_pid" ] && [ "$__orca_pid" != "0" ] && [ "$__orca_pid" != "1" ]; do',
    '    __orca_value=""',
    '    if [ -r "/proc/$__orca_pid/environ" ]; then',
    '      __orca_value=$(tr "\\000" "\\n" < "/proc/$__orca_pid/environ" 2>/dev/null | __orca_lookup_env "$__orca_name")',
    '    fi',
    '    if [ -z "$__orca_value" ]; then',
    '      __orca_value=$(ps eww -p "$__orca_pid" -o command= 2>/dev/null | tr " " "\\n" | __orca_lookup_env "$__orca_name")',
    '    fi',
    '    if [ -n "$__orca_value" ]; then',
    '      printf "%s\\n" "$__orca_value"',
    '      return 0',
    '    fi',
    '    __orca_pid=$(ps -o ppid= -p "$__orca_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__orca_fill_from_ancestor() {',
    '  __orca_name="$1"',
    '  case "$__orca_name" in',
    '    ORCA_AGENT_HOOK_ENDPOINT) [ -z "${CODING_AGENT_AGENT_HOOK_ENDPOINT-${ORCA_AGENT_HOOK_ENDPOINT:-}}" ] || return 0 ;;',
    '    ORCA_AGENT_HOOK_PORT) [ -z "${CODING_AGENT_AGENT_HOOK_PORT-${ORCA_AGENT_HOOK_PORT:-}}" ] || return 0 ;;',
    '    ORCA_AGENT_HOOK_TOKEN) [ -z "${CODING_AGENT_AGENT_HOOK_TOKEN-${ORCA_AGENT_HOOK_TOKEN:-}}" ] || return 0 ;;',
    '    ORCA_AGENT_HOOK_ENV) [ -z "${CODING_AGENT_AGENT_HOOK_ENV-${ORCA_AGENT_HOOK_ENV:-}}" ] || return 0 ;;',
    '    ORCA_AGENT_HOOK_VERSION) [ -z "${CODING_AGENT_AGENT_HOOK_VERSION-${ORCA_AGENT_HOOK_VERSION:-}}" ] || return 0 ;;',
    '    ORCA_PANE_KEY) [ -z "${CODING_AGENT_PANE_KEY-${ORCA_PANE_KEY:-}}" ] || return 0 ;;',
    '    ORCA_TAB_ID) [ -z "${CODING_AGENT_TAB_ID-${ORCA_TAB_ID:-}}" ] || return 0 ;;',
    '    ORCA_WORKTREE_ID) [ -z "${CODING_AGENT_WORKTREE_ID-${ORCA_WORKTREE_ID:-}}" ] || return 0 ;;',
    '    ORCA_AGENT_LAUNCH_TOKEN) [ -z "${CODING_AGENT_AGENT_LAUNCH_TOKEN-${ORCA_AGENT_LAUNCH_TOKEN:-}}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __orca_value=$(__orca_read_ancestor_var "$__orca_name") || return 0',
    '  [ -n "$__orca_value" ] && export "$__orca_name=$__orca_value" "CODING_AGENT_${__orca_name#ORCA_}=$__orca_value"',
    '}',
    '__orca_endpoint_value() {',
    '  __orca_endpoint_name="$1"',
    '  __orca_endpoint_path="$2"',
    '  sed -n "s/^${__orca_endpoint_name}=//p" "$__orca_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__orca_fill_from_endpoint_file() {',
    '  __orca_endpoint_path="$1"',
    '  [ -r "$__orca_endpoint_path" ] || return 0',
    '  __orca_endpoint_port=$(__orca_endpoint_value ORCA_AGENT_HOOK_PORT "$__orca_endpoint_path")',
    '  if [ -n "${CODING_AGENT_AGENT_HOOK_PORT-${ORCA_AGENT_HOOK_PORT:-}}" ] && [ -n "$__orca_endpoint_port" ] && [ "$__orca_endpoint_port" != "${CODING_AGENT_AGENT_HOOK_PORT-$ORCA_AGENT_HOOK_PORT}" ]; then',
    '    return 0',
    '  fi',
    '  for __orca_endpoint_name in ORCA_AGENT_HOOK_PORT ORCA_AGENT_HOOK_TOKEN ORCA_AGENT_HOOK_ENV ORCA_AGENT_HOOK_VERSION; do',
    '    eval "__orca_current=\\${$__orca_endpoint_name:-}"',
    '    [ -z "$__orca_current" ] || continue',
    '    __orca_endpoint_value=$(__orca_endpoint_value "$__orca_endpoint_name" "$__orca_endpoint_path")',
    '    [ -n "$__orca_endpoint_value" ] && export "$__orca_endpoint_name=$__orca_endpoint_value" "CODING_AGENT_${__orca_endpoint_name#ORCA_}=$__orca_endpoint_value"',
    '  done',
    '}',
    '# Recover pane/hook metadata from the parent TUI after Command Code sanitizes hook env.',
    'for __orca_name in ORCA_AGENT_HOOK_ENDPOINT ORCA_AGENT_HOOK_PORT ORCA_AGENT_HOOK_TOKEN ORCA_AGENT_HOOK_ENV ORCA_AGENT_HOOK_VERSION ORCA_PANE_KEY ORCA_TAB_ID ORCA_WORKTREE_ID ORCA_AGENT_LAUNCH_TOKEN; do',
    '  __orca_fill_from_ancestor "$__orca_name"',
    'done',
    'if [ -n "${CODING_AGENT_AGENT_HOOK_ENDPOINT-$ORCA_AGENT_HOOK_ENDPOINT}" ] && [ -r "${CODING_AGENT_AGENT_HOOK_ENDPOINT-$ORCA_AGENT_HOOK_ENDPOINT}" ]; then',
    '  __orca_fill_from_endpoint_file "${CODING_AGENT_AGENT_HOOK_ENDPOINT-$ORCA_AGENT_HOOK_ENDPOINT}"',
    'fi',
    '# Recover stripped token metadata by matching the preserved loopback port.',
    'if [ -z "${CODING_AGENT_AGENT_HOOK_TOKEN-$ORCA_AGENT_HOOK_TOKEN}" ] && [ -n "${CODING_AGENT_AGENT_HOOK_PORT-$ORCA_AGENT_HOOK_PORT}" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/orca-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/orca-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/orca-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/orca/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(__orca_lookup_env ORCA_AGENT_HOOK_PORT < "$endpoint")',
    '    if [ "$endpoint_port" = "${CODING_AGENT_AGENT_HOOK_PORT-$ORCA_AGENT_HOOK_PORT}" ]; then',
    '      __orca_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "${CODING_AGENT_AGENT_HOOK_PORT-$ORCA_AGENT_HOOK_PORT}" ] || [ -z "${CODING_AGENT_AGENT_HOOK_TOKEN-$ORCA_AGENT_HOOK_TOKEN}" ] || [ -z "${CODING_AGENT_PANE_KEY-$ORCA_PANE_KEY}" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Bound stalled posts and pipe large payloads through stdin to avoid EDR command-line false positives.
    `printf '%s' "$payload" | ${posixCurlCommand()} -sS -X POST "http://127.0.0.1:\${CODING_AGENT_AGENT_HOOK_PORT-\${ORCA_AGENT_HOOK_PORT}}/hook/command-code" \\`,
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-Orca-Agent-Hook-Token: ${CODING_AGENT_AGENT_HOOK_TOKEN-${ORCA_AGENT_HOOK_TOKEN}}" \\',
    '  --data-urlencode "paneKey=${CODING_AGENT_PANE_KEY-${ORCA_PANE_KEY}}" \\',
    '  --data-urlencode "tabId=${CODING_AGENT_TAB_ID-${ORCA_TAB_ID}}" \\',
    '  --data-urlencode "launchToken=${CODING_AGENT_AGENT_LAUNCH_TOKEN-${ORCA_AGENT_LAUNCH_TOKEN}}" \\',
    '  --data-urlencode "worktreeId=${CODING_AGENT_WORKTREE_ID-${ORCA_WORKTREE_ID}}" \\',
    '  --data-urlencode "env=${CODING_AGENT_AGENT_HOOK_ENV-${ORCA_AGENT_HOOK_ENV}}" \\',
    '  --data-urlencode "version=${CODING_AGENT_AGENT_HOOK_VERSION-${ORCA_AGENT_HOOK_VERSION}}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
