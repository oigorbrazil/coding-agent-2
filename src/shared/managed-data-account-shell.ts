import { fishAppEnvRestore } from './app-env-script'
export const MANAGED_DATA_ACCOUNT_POSIX_RESTORE = `if [[ -n "\${CODING_AGENT_DATA_ACCOUNT_DATA_HOME-\${ORCA_DATA_ACCOUNT_DATA_HOME:-}}" ]]; then
  export XDG_DATA_HOME="\${CODING_AGENT_DATA_ACCOUNT_DATA_HOME-\${ORCA_DATA_ACCOUNT_DATA_HOME}}"
  export XDG_STATE_HOME="\${CODING_AGENT_DATA_ACCOUNT_STATE_HOME-\${ORCA_DATA_ACCOUNT_STATE_HOME}}"
  if [[ "\${CODING_AGENT_DATA_ACCOUNT_PROVIDER-\${ORCA_DATA_ACCOUNT_PROVIDER:-}}" == opencode ]]; then
    export OPENCODE_AUTH_CONTENT=""
    export OPENCODE_DB="opencode.db"
  fi
fi`

export const MANAGED_DATA_ACCOUNT_POWERSHELL_RESTORE = `if ($(if (Test-Path Env:CODING_AGENT_DATA_ACCOUNT_DATA_HOME) { $env:CODING_AGENT_DATA_ACCOUNT_DATA_HOME } else { $env:ORCA_DATA_ACCOUNT_DATA_HOME })) {
  $env:XDG_DATA_HOME = $(if (Test-Path Env:CODING_AGENT_DATA_ACCOUNT_DATA_HOME) { $env:CODING_AGENT_DATA_ACCOUNT_DATA_HOME } else { $env:ORCA_DATA_ACCOUNT_DATA_HOME })
  $env:XDG_STATE_HOME = $(if (Test-Path Env:CODING_AGENT_DATA_ACCOUNT_STATE_HOME) { $env:CODING_AGENT_DATA_ACCOUNT_STATE_HOME } else { $env:ORCA_DATA_ACCOUNT_STATE_HOME })
  if ($(if (Test-Path Env:CODING_AGENT_DATA_ACCOUNT_PROVIDER) { $env:CODING_AGENT_DATA_ACCOUNT_PROVIDER } else { $env:ORCA_DATA_ACCOUNT_PROVIDER }) -eq 'opencode') {
    $env:OPENCODE_AUTH_CONTENT = ''
    $env:OPENCODE_DB = 'opencode.db'
  }
}`

export const MANAGED_DATA_ACCOUNT_FISH_RESTORE = `${fishAppEnvRestore(['DATA_ACCOUNT_DATA_HOME', 'DATA_ACCOUNT_STATE_HOME', 'DATA_ACCOUNT_PROVIDER'])}
        if set -q ORCA_DATA_ACCOUNT_DATA_HOME; and test -n "$ORCA_DATA_ACCOUNT_DATA_HOME"
            set -gx XDG_DATA_HOME "$ORCA_DATA_ACCOUNT_DATA_HOME"
            set -gx XDG_STATE_HOME "$ORCA_DATA_ACCOUNT_STATE_HOME"
            if test "$ORCA_DATA_ACCOUNT_PROVIDER" = opencode
                set -gx OPENCODE_AUTH_CONTENT ''
                set -gx OPENCODE_DB opencode.db
            end
        end`
